/** Build a checksummed, config-only Cloudflare Worker release artifact. */
import { createHash } from 'node:crypto'
import { existsSync } from 'node:fs'
import { cp, mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'
import packageJson from '../package.json' with { type: 'json' }
import { MIGRATIONS } from '../src/schema.ts'

const appRoot = dirname(dirname(fileURLToPath(import.meta.url)))
const workspaceRoot = dirname(dirname(appRoot))
const version = packageJson.version
const outputDir = join(workspaceRoot, 'dist', 'releases', version)
const stagingDir = `${outputDir}.tmp`
const bundleName = `statusping-cloudflare-${version}.js`
const wrangler = process.platform === 'win32'
  ? join(workspaceRoot, 'node_modules', '.bin', 'wrangler.cmd')
  : join(workspaceRoot, 'node_modules', '.bin', 'wrangler')

function sha256(content: Uint8Array): string {
  return createHash('sha256').update(content).digest('hex')
}

/**
 * A release bundle is public. The release worker deliberately reads all
 * credentials at runtime, but guard against a future bundler/config mistake
 * by rejecting any artifact containing a secret value supplied to this build.
 * Only values are scanned; an error names the environment key, never its value.
 */
function assertNoBuildSecrets(files: Record<string, Uint8Array>) {
  const candidates = Object.entries(process.env).filter(([name, value]) =>
    /(?:secret|token|password|api[_-]?key|credential|private[_-]?key)/i.test(name) && (value?.length ?? 0) >= 8,
  ) as [string, string][]
  for (const [name, value] of candidates) {
    for (const [file, bytes] of Object.entries(files)) {
      if (Buffer.from(bytes).includes(Buffer.from(value))) {
        throw new Error(`Release artifact ${file} contains a value from ${name}; aborting before publication`)
      }
    }
  }
}

function migrationsSql(): string {
  const parts = [
    '-- Generated by npm run release:bundle. Do not edit by hand.',
    '-- Applies the complete StatusPing schema to a fresh D1 database.',
    'BEGIN;',
  ]
  for (const [index, migration] of MIGRATIONS.entries()) {
    parts.push(`-- Migration ${index + 1}`)
    parts.push(...migration.map((statement) => `${statement};`))
    parts.push(
      `INSERT INTO meta (key, value) VALUES ('schema_version', '${index + 1}') ` +
        "ON CONFLICT (key) DO UPDATE SET value = excluded.value;",
    )
  }
  parts.push('COMMIT;', '')
  return parts.join('\n')
}

async function main() {
  if (!existsSync(wrangler)) throw new Error('Wrangler is not installed; run npm ci first')
  await rm(stagingDir, { recursive: true, force: true })
  await mkdir(stagingDir, { recursive: true })

  const workerOut = join(stagingDir, 'worker')
  const result = spawnSync(wrangler, [
    'deploy', '--dry-run', '--outdir', workerOut, '--config', 'adapters/cloudflare/release-wrangler.toml',
  ], { cwd: appRoot, encoding: 'utf8' })
  if (result.status !== 0) {
    throw new Error(`Wrangler bundle build failed:\n${result.stdout}\n${result.stderr}`)
  }
  const builtWorker = join(workerOut, 'release-worker.js')
  if (!existsSync(builtWorker)) throw new Error(`Expected Wrangler output was not found: ${builtWorker}`)
  await cp(builtWorker, join(stagingDir, bundleName))
  // The sourcemap and Wrangler's helper README are useful while building, but are
  // not part of the deployable, checksummed release contract.
  await rm(workerOut, { recursive: true, force: true })
  await writeFile(join(stagingDir, 'migrations.sql'), migrationsSql(), 'utf8')

  const metadata = {
    version,
    entrypoint: bundleName,
    configuration: 'STATUSPING_CONFIG',
    compatibilityDate: '2026-10-01',
    cron: '* * * * *',
    bindings: [
      { name: 'DB', type: 'd1_database', required: true },
      { name: 'REGIONAL_PROBE', type: 'durable_object_namespace', required: false },
      { name: 'SEND_EMAIL', type: 'send_email', required: false },
    ],
    requiredVariables: ['STATUSPING_CONFIG'],
    optionalVariables: ['STATUSPING_ROLE', 'STATUSPING_EMAIL_FROM'],
    secrets: [
      'PING_TOKENS', 'BASIC_AUTH_USERS', 'SESSION_SECRET', 'ADMIN_TOKEN', 'ACK_SECRET',
      'SUBSCRIBER_TOKEN_SECRET', 'PUSHOVER_APP_TOKEN', 'PUSHOVER_USER_KEY',
      'TELEGRAM_BOT_TOKEN', 'TELEGRAM_CHAT_ID', 'NTFY_TOKEN', 'TICK_SECRET',
    ],
  }
  await writeFile(join(stagingDir, 'metadata.json'), `${JSON.stringify(metadata, null, 2)}\n`, 'utf8')

  const artifactContents = Object.fromEntries(await Promise.all([bundleName, 'migrations.sql', 'metadata.json'].map(async (name) => [name, await readFile(join(stagingDir, name))]))) as Record<string, Uint8Array>
  assertNoBuildSecrets(artifactContents)

  const fileNames = [bundleName, 'migrations.sql', 'metadata.json']
  const files = Object.fromEntries(await Promise.all(fileNames.map(async (name) => {
    const bytes = artifactContents[name]!
    return [name, { sha256: sha256(bytes), bytes: bytes.byteLength }]
  })))
  const manifest = { version, files }
  await writeFile(join(stagingDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8')

  await rm(outputDir, { recursive: true, force: true })
  await rename(stagingDir, outputDir)
  process.stdout.write(`Release bundle written to ${outputDir}\n`)
}

void main().catch((error) => {
  console.error(error instanceof Error ? error.message : error)
  process.exitCode = 1
})
